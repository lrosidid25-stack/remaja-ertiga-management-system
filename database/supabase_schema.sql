-- ============================================================
-- FUNGSI EKSEKUSI SQL
-- ============================================================
create or replace function public.re_query(q text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  body text := btrim(q);
  first_word text;
  dml text;
  result jsonb;
  tbl text;
begin
  if right(body, 1) = ';' then body := btrim(left(body, length(body) - 1)); end if;
  if position(';' in body) > 0 then
    raise exception 'Beberapa statement dalam satu permintaan tidak diizinkan';
  end if;
  if body ~* '(--|/\*|\mpg_catalog\M|\minformation_schema\M|\mpg_shadow\M|\mpg_authid\M|\mpg_read_file\M|\mpg_sleep\M|\mcopy\M|\mlo_import\M|\mdblink\M|\mcreate[[:space:]]+role\M|\malter[[:space:]]+role\M|\mgrant\M|\mrevoke\M)' then
    raise exception 'Pola SQL tidak diizinkan';
  end if;

  first_word := upper(split_part(body, ' ', 1));
  if first_word not in ('SELECT','INSERT','UPDATE','DELETE','WITH') then
    raise exception 'Perintah % tidak diizinkan', first_word;
  end if;

  for tbl in
    select m[1] from regexp_matches(body, '(?:from|join|into|update)[[:space:]]+([a-zA-Z_][a-zA-Z0-9_]*)', 'gi') as t(m)
  loop
    if left(lower(tbl), 3) <> 're_' then
      raise exception 'Tabel % tidak diizinkan', tbl;
    end if;
  end loop;

  if first_word in ('SELECT','WITH') then
    execute format('select coalesce(jsonb_agg(to_jsonb(t)), ''[]''::jsonb) from (%s) t', body) into result;
    return coalesce(result, '[]'::jsonb);
  end if;

  if body ~* '[^a-zA-Z0-9_]returning[^a-zA-Z0-9_]' then
    dml := body;
  else
    dml := body || ' returning *';
  end if;

  execute format('with d as (%s) select coalesce(jsonb_agg(to_jsonb(d)), ''[]''::jsonb) from d', dml) into result;
  return coalesce(result, '[]'::jsonb);
end;
$fn$;

-- Hanya service_role (server Vercel) yang boleh mengeksekusi
revoke all on function public.re_query(text) from public;
revoke all on function public.re_query(text) from anon, authenticated;
grant execute on function public.re_query(text) to service_role;

revoke all on all tables in schema public from anon, authenticated;
grant all on all tables in schema public to service_role;
grant all on all sequences in schema public to service_role;
