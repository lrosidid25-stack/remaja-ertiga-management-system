-- Aplikasi memakai schema "public" dengan prefix tabel "re_" agar tidak
-- bentrok dengan tabel lain di project yang sama. Semua SQL aplikasi
-- dikirim lewat fungsi re_query() sehingga JOIN, subquery, agregat dan
-- ON CONFLICT tetap berjalan seperti di SQLite.
--
-- Keamanan: fungsi re_query() hanya bisa dipanggil service_role, dan
-- akses tabel dicabut dari anon/authenticated. Aplikasi memanggilnya
-- dengan service key yang disimpan sebagai env var di Vercel.
-- ============================================================

